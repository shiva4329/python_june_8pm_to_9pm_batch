# Arithmetic operators :

# + = addition
# - = substraction
# * = multiplication
# / = division(result in decimal)
# // = floor division(result with out decimal)
# % = Modulus (result : reminder)
# ** = Power operation





x = 10
y = 20

print(x+y) # addition
print(x-y) # substraction
print(y-x) # substraction
print(x*2) # multiplication
print(x/2) # returns quotient in float
print(x//2) # returns quotient in integer
print(x%2) # returns reminder
print(9%2)
print(x**2) # power operation